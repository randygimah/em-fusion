def _in_list(column: str, values: tuple[str, ...]) -> str:
    """A readable `col IN ('a', 'b')` for a CHECK constraint."""
    rendered = ", ".join(f"'{value}'" for value in values)
    return f"{column} IN ({rendered})"


#: Added as explicit DDL rather than through GeoAlchemy2. That library's value
#: is at query time -- teaching SQLAlchemy to read WKB back into Python -- which
#: is `db-003`'s problem, not this revision's. Here it would add a dependency to
#: hide two lines of DDL that are clearer written out, in a file that is
#: hand-written by design because autogenerate cannot handle these columns
#: anyway. Point/Polygon and SRID 4326 are visible in the source rather than
#: inferred from a constructor's defaults.
GEOMETRY_COLUMNS = (
    ("observations", "location", "Point"),
    ("anomalies", "affected_area", "Polygon"),
)


def _add_geometry_columns() -> None:
    """Add the geometry columns and their GiST indexes.

    Without the index the clustering query in `db-004` still returns correct
    answers, by sequential scan -- it fails as a performance claim rather than
    a correctness one, which is the kind of defect that survives every
    functional test. Created here so the two cannot drift apart.
    """
    for table, column, geometry_type in GEOMETRY_COLUMNS:
        op.execute(
            f"ALTER TABLE {table} "
            f"ADD COLUMN {column} geometry({geometry_type}, 4326) NOT NULL"
        )
        op.execute(f"CREATE INDEX ix_{table}_{column} ON {table} USING GIST ({column})")


def _require_postgis() -> None:
    """Fail at migration time if PostGIS is absent, naming the extension.

    Deliberately a check and not `CREATE EXTENSION IF NOT EXISTS`. Creating it
    needs superuser and is the container image's job, and more importantly a
    migration that creates it can never *fail* for its absence -- which is the
    failure case `db-001` exists to guard. Without this the schema builds
    happily, the service reports healthy, and the first spatial query dies with
    `type "geography" does not exist`, a long way from the cause.
    """
    installed = (
        op.get_bind()
        .execute(sa.text("SELECT 1 FROM pg_extension WHERE extname = 'postgis'"))
        .scalar()
    )
    if not installed:
        raise RuntimeError(
            "The postgis extension is not installed in this database. "
            "Migrations assert it rather than creating it: run "
            "CREATE EXTENSION postgis as a superuser, or let the "
            "postgis/postgis image initialise a fresh data directory. "
            "See docs/qa.md section 18."
        )


